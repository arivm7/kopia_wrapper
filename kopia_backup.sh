#!/usr/bin/env bash
# kopia_backup.sh
# ------------------------------------------------------------------------------
# Скрипт регулярного резервного копирования каталогов и файлов из списка
# SOURCE_PATHS (см. kopia_common.sh) в репозиторий kopia.
#
# При первом запуске подключается к существующему репозиторию или создаёт
# новый (если он ещё не был инициализирован). При каждом запуске создаёт
# снапшот для каждого пути из SOURCE_PATHS, применяет политику хранения
# и выполняет лёгкое обслуживание репозитория.
#
# Дополнительно рядом с репозиторием сохраняется restore-kit — набор
# файлов (repository.config, .kopia-password, .kopia_pass) и README,
# достаточный для восстановления архива на другой машине без ручного
# ввода пароля. См. RESTORE_KIT_MODE в kopia_common.sh.
#
# Требует root-доступ (часть путей из SOURCE_PATHS доступна на чтение
# только root: /etc, /var/spool/cron, /var/www и т.д.). Если скрипт запущен
# обычным пользователем, он сам перезапускается через sudo (require_root).
#
# Поведение при отсутствии конфига:
#     Если $CONFIG_FILE не существует, вызывается save_config_file(),
#     которая создаёт ШАБЛОН конфига (с дефолтными путями, не
#     отражающими реальную структуру текущей системы) и ЗАВЕРШАЕТ
#     скрипт с кодом 0 и сообщением «отредактируйте и запустите
#     заново». Это сделано намеренно: пользователь должен осознанно
#     пройти через редактирование, а не запустить бэкап с дефолтными
#     путями, которые могут оказаться неверными.
#     После этого пользователь запускает `-ec` ещё раз — теперь
#     конфиг существует, и edit_config_file открывает его в редакторе.
# 
# 
# # Для доступа к репозиторию kopia (чтение/запись/вход в каталоги) для группы user, 
# # в которую входит обычный пользователь, выполняются следующие действия (один раз, при настройке):
# 
# # 1. Сменить группу существующих файлов и каталогов
# sudo chown -R root:user /path/to/repo
# 
# # 2. Дать группе права на чтение/запись/вход в каталоги
# sudo chmod -R g+rwX /path/to/repo
# 
# # 3. Включить наследование группы для НОВЫХ файлов
# # Выполнить комианду для каждого каталога по очередив репозитории (рекурсивно):
# sudo find /path/to/repo -type d -exec chmod g+s {} \; 
# # или
# # Выполнить команду для всех каталогов в репозитории обдновременно:
# sudo find /path/to/repo -type d -exec chmod g+s {} +
# 
# 
# # Посмотреть атрибуты каталога (sgid отображается как 's' в позиции группы)
# ls -ld /path/to/repo
# # drwxr-sr-x  ... root user  ... /path/to/repo
# #       ^
# #       здесь 's' — SGID установлен
# 
# # Создать тестовый файл от root и проверить его группу
# sudo touch /path/to/repo/testfile
# ls -l /path/to/repo/testfile
# # -rw-r--r--  ... root user  ... testfile
# #                      ^^^^
# #                      группа user — унаследована от каталога
#
# ------------------------------------------------------------------------------

set -uo pipefail



APP_TITLE="Скрипт создания резервной копии. Оёртка для Kopia - Fast And Secure Open-Source Backup"

APP_NAME="$(basename "$0")"
APP_DIR="$(cd "$(dirname "$0")" && pwd)"    # Папка размещения скрипта
# shellcheck disable=SC2034
FILE_NAME="${APP_NAME%.*}"                  # Убираем расширение (если есть)




# ---- Справка и использование
print_usage() {
    echo "Использование: ${APP_NAME} [-h|--help] [-u|--usage] [-v|--version] [-ec|--edit_config]"
}



print_help() {
    print_usage
cat <<EOF

${APP_TITLE}
${APP_NAME} — резервное копирование каталогов и файлов через kopia.

Ключи:
  -h, --help          показать эту справку и выйти
  -u, --usage         показать краткую строку использования и выйти
  -v, --version       показать версию скрипта и выйти
  -ec, --edit_config  открыть конфиг-файл обёртки в редакторе (EDITOR из
                      ${CONFIG_FILE}). 
                      После сохранения запустите скрипт заново.
Описание:
  При каждом запуске скрипт выводит путь к репозиторию, конфиг-файлу
  обёртки и конфигу подключения kopia — для диагностики, какой именно
  репозиторий и конфиг используются.

  Скрипт подключается (или, при первом запуске, создаёт) к репозиторию
  kopia, указанному в kopia_common.sh (переменная REPO_PATH), затем
  создаёт снапшоты для всех путей из массива SOURCE_PATHS, применяет
  к ним политику хранения (30 суточных / 12 недельных / 12 месячных
  снапшотов) и выполняет лёгкое обслуживание репозитория.

  Рядом с репозиторием сохраняется restore-kit — набор файлов, достаточный
  для восстановления архива на другой машине без ручного ввода пароля.
  Куда именно класть restore-kit (внутри репозитория, рядом с ним или
  не класть вовсе), задаётся переменной RESTORE_KIT_MODE в kopia_common.sh.
  ВНИМАНИЕ: restore-kit содержит пароль репозитория (в открытом виде и в
  base64-обфускации). Храните его так же тщательно, как сами данные.

  Полное обслуживание (kopia maintenance run --full) в этот скрипт
  не входит намеренно — его рекомендуется запускать отдельным
  cron-заданием раз в неделю.

  Часть путей из SOURCE_PATHS доступна на чтение только root (/etc,
  /var/spool/cron, /var/www и т.д.). Если скрипт запущен обычным
  пользователем, он сам перезапускается через sudo (см. require_root
  в kopia_common.sh) — вызывать sudo вручную не обязательно.

Файлы:
  kopia_common.sh   — общие настройки: пути репозитория, список
                      источников резервного копирования, список
                      требуемых программ, параметры restore-kit.
Версия: ${APP_VERSION}
${COPYRIGHT}
EOF
}



# ---- Подключаем общий конфиг -------------------------------------------------
# shellcheck disable=SC1091
source "${APP_DIR}/kopia_common.sh"



# ---- Разбор аргументов командной строки -------------------------------------
# Обрабатываем только первый аргумент — этого достаточно для стандартных
# информационных ключей, других аргументов скрипт не принимает.
case "${1:-}" in
    -v|--version)
        print_version
        exit 0
        ;;
    -h|--help)
        print_help
        exit 0
        ;;
    -u|--usage)
        print_usage
        exit 0
        ;;
    -ec|--edit_config)
        edit_config_file
        # После редактирования — выходим, чтобы пользователь запустил
        # скрипт заново и применил изменения.
        exit_with_msg "Конфиг-файл отредактирован: ${CONFIG_FILE}. Запустите скрипт заново, чтобы применить изменения." 0
        ;;
esac



echo ""
echo ""
echo ""
echo "==================================="
date



# ---- Чтение/создание пользовательского конфига -------------------------------
# Выполняется ДО эскалации прав, поэтому файл создаётся и остаётся
# собственностью обычного пользователя — редактировать его можно без sudo.
read_config_file



# Обновляем эталонный source_paths.txt в CONFIG_PATH (только при изменении
# SOURCE_PATHS). Дальше write_restore_kit просто скопирует его в kit,
# как и остальные файлы из RESTORE_KIT_FILES.
write_source_paths_file



echo "Путь репозитория     : ${REPO_PATH}"
echo "Конфигурация обёртки : ${CONFIG_FILE}"
echo "Конфигурация kopia   : ${KOPIA_CONFIG}"
echo "Список путей         : ${KOPIA_PATHS_FILE}"
echo ""



# ---- Самоповышение прав ------------------------------------------------------
# Если скрипт запущен обычным пользователем — перезапускаем его через sudo.
# Все дальнейшие операции (чтение /etc, /var/www и т.д., создание снапшотов)
# выполняются уже от root. Справка/версия и чтение конфига выше отработали
# без sudo.
require_root "$@"



# ---- 0. Проверка необходимых программ ---------------------------------------
# При отсутствии программ, доступных через apt, будет предложена установка.
# При отказе или при отсутствии программ, требующих ручной установки,
# скрипт завершится с кодом 1 (см. kopia_common.sh).
check_required_packages



# ---- 0.1. Проверка файла с паролем репозитория -------------------------------
# Проверяется при каждом запуске: файл должен существовать, принадлежать
# root и иметь права 600. При несоответствии — ошибка и exit 1.
check_kopia_password_file



# ---- 1. Проверка и подключение / создание репозитория -----------------------
# Сначала смотрим, не подключён ли репозиторий уже (обычная ситуация при
# повторных запусках — тогда пароль не запрашивается благодаря сохранённой
# сессии в KOPIA_CONFIG).
if kopia repository status --config-file "$KOPIA_CONFIG" &>/dev/null; then
    echo "Репозиторий уже подключён."
else
    # Не подключён — проверяем, существует ли репозиторий физически на диске
    if [[ -f "$REPO_PATH/kopia.repository.f" || -f "$REPO_PATH/kopia.repository" ]]; then

        echo "Репозиторий найден, подключаемся..."
        # Пароль репозитория хранится в защищённом файле (chmod 600, root:root),
        # чтобы неинтерактивные запуски (cron) не зависали на запросе пароля.
        # Наличие и права файла уже проверены выше функцией check_kopia_password_file.
        KOPIA_PASSWORD="$(cat "$KOPIA_PASSWORD_FILE")"
        export KOPIA_PASSWORD
        kopia repository connect filesystem \
            --path "$REPO_PATH" \
            --config-file "$KOPIA_CONFIG" || {
                exit_with_msg "ОШИБКА: не удалось подключиться к репозиторию" 1
            }
    else
        echo "Репозиторий не найден, создаём новый..."
        mkdir -p "$REPO_PATH"
        kopia repository create filesystem \
            --path "$REPO_PATH" \
            --config-file "$KOPIA_CONFIG" || {
                exit_with_msg "ОШИБКА: не удалось создать репозиторий" 1
            }
    fi
fi



# ---- 1.1. Сохранение restore-kit рядом с репозиторием -----------------------
# Кладём рядом с архивом всё, что нужно для восстановления на другой
# машине: repository.config, repository.config.kopia-password, .kopia_pass
# и README.txt с инструкцией. Без этих файлов восстановление из cron
# невозможно (интерактивного ввода пароля не предусмотрено).
#
# Куда именно класть restore-kit, задаётся RESTORE_KIT_MODE в kopia_common.sh:
#   "in"   — $REPO_PATH/restore_kit/        (по умолчанию)
#   "out"  — ${REPO_PATH}.restore_kit/      (рядом, можно увезти отдельно)
#   "none" — не сохранять
#
# ВНИМАНИЕ: restore-kit содержит пароль репозитория. Храните его так же
# тщательно, как сами данные.
write_restore_kit "$REPO_PATH"



# ---- 2. Снапшоты и политика хранения для каждого пути ------------------------
FAILED=()

for DIR in "${SOURCE_PATHS[@]}"; do

    if [[ -d "$DIR" ]]; then
        echo "Бэкап каталога: $DIR"
    elif [[ -f "$DIR" ]]; then
        echo "Бэкап файла: $DIR"
    else
        echo "ПРОПУСК: $DIR не найден" >&2
        continue
    fi

    if ! kopia snapshot create "$DIR" --config-file "$KOPIA_CONFIG"; then
        echo "ОШИБКА: снапшот для $DIR не создан" >&2
        FAILED+=("$DIR")
        continue
    fi

    # Политика хранения: 30 ежедневных, 12 еженедельных, 12 ежемесячных снапшотов
    kopia policy set "$DIR" --config-file "$KOPIA_CONFIG" --keep-daily 30 --keep-weekly 12 --keep-monthly 12
done



# ---- 3. Лёгкое обслуживание репозитория --------------------------------------
# Полное обслуживание (--full) сюда намеренно не входит — запускайте его
# отдельным cron-заданием раз в неделю: kopia maintenance run --full
kopia maintenance run --config-file "$KOPIA_CONFIG"



# ---- 3.1. Постобработка прав репозитория ------------------------------------
# Назначаем владельца/группу/права на файлы репозитория и restore-kit.
# Нужно, если бэкап работает от root, а читать архив должен другой
# пользователь (например, по SSH). Управляется переменными
# POSTPROCESS_* в kopia_common.sh; по умолчанию отключено.
# Выполняется от root (после require_root), sudo не нужен.
postprocess_repo_permissions "$REPO_PATH"



# ---- 4. Итог ------------------------------------------------------------------
if (( ${#FAILED[@]} > 0 )); then
    exit_with_msg "Бэкап завершён с ошибками для: ${FAILED[*]}" 1
fi

exit 0
